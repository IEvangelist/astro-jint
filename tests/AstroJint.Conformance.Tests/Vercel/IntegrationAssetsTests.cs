using System.Net;

namespace AstroJint.Conformance.Vercel;

/// <summary>
/// Port of <c>packages/integrations/vercel/test/integration-assets.test.ts</c>. Upstream builds a site with the sitemap
/// integration, once with static and once with server output, and reads <c>sitemap-index.xml</c> from the static folder
/// of the Vercel output: the files that an integration generates must be moved to the place that is served.
/// <para>
/// Differences from upstream: the static folder of the Vercel output is the <c>client</c> folder of this adapter's output,
/// and the test also requests the file from the host, which must answer it with the same content. The two builds are the
/// shared sites of the fixtures <c>vercel-static</c> and <c>vercel-server</c>, which both have the sitemap integration.
/// </para>
/// </summary>
[Trait("Upstream", "vercel/integration-assets.test.ts")]
public class IntegrationAssetsTests(SiteHost sites)
{
    private const string SitemapIndex = "<sitemapindex xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">";

    [Fact(DisplayName = "moves static assets generated by integrations to the correct location: static output")]
    public async Task StaticOutput_HasTheSitemapOfTheIntegration() =>
        await AssertSitemapAsync(await sites.StaticAsync());

    [Fact(DisplayName = "moves static assets generated by integrations to the correct location: server output")]
    public async Task ServerOutput_HasTheSitemapOfTheIntegration() =>
        await AssertSitemapAsync(await sites.ServerAsync());

    private static async Task AssertSitemapAsync(ConformanceSite site)
    {
        var file = await File.ReadAllTextAsync(Path.Combine(site.DistPath, "client", "sitemap-index.xml"));

        using var response = await site.GetAsync("/sitemap-index.xml");

        Assert.Contains(SitemapIndex, file);
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        Assert.Equal(file, await response.ReadTextAsync());
    }
}
